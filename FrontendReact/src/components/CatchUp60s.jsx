import React, { useState } from 'react';
import { fetchCatchUp } from '../services/api';


export default function CatchUp60s() {
  const [selectedOver, setSelectedOver] = useState(12);
  const [isLoading,    setIsLoading]    = useState(false);
  const [summary,      setSummary]      = useState(null);
  const [error,        setError]        = useState(null);
  const [followup,     setFollowup]     = useState(null);

  const QUICK_QUESTIONS = [
    'Who bowled the most wickets so far?',
    'Which over had the highest run rate?',
    'Who is the leading scorer right now?'
  ];

  async function handleCatchUp() {
    setIsLoading(true);
    setError(null);
    setFollowup(null);
    try {
      const text = await fetchCatchUp(selectedOver);
      setSummary(text);
    } catch (err) {
      console.warn('CatchUp fetch failed, using fallback:', err.message);
      setError('Backend offline — showing demo summary');
      setSummary(
        `[Demo Brief] Up to Over ${selectedOver}: India are ${selectedOver * 8}/2. Rohit Sharma (${selectedOver * 5}*) anchors while middle-order keeps the run rate near ${(selectedOver * 8 / selectedOver).toFixed(1)}. Required rate is manageable at ${(185 - selectedOver * 8) > 0 ? ((185 - selectedOver * 8) / (20 - selectedOver)).toFixed(1) : '0.0'} per over.`
      );
    } finally {
      setIsLoading(false);
    }
  }

  function handleQuickQuestion(q) {
    setFollowup({
      question: q,
      answer: 'Stat check: Rohit Sharma leads with 78 (44), Boult has taken 2/28 in his 4 overs, and Over 13 yielded 22 runs.'
    });
  }

  return (
    <div>
      <div className="feature-header">
        <div className="feature-title">
          <h2>⏱️ Catch-Up in 60 Seconds</h2>
          <p>Drag to your arrival over • AI brief generated by Java CatchUpService</p>
        </div>
      </div>

      <div className="glass-card" style={{ marginBottom: '20px' }}>
        <div className="card-heading">When Did You Tune In?</div>
        <div className="card-subheading">
          Slide to your arrival over — calls GET /api/match/catchup/{selectedOver} on backend
        </div>

        <div className="slider-meta-row">
          <span>Over 1</span>
          <span style={{ color: '#00e87a', fontWeight: '800', fontFamily: 'var(--font-mono)' }}>
            You joined: Over {selectedOver}.0
          </span>
          <span>Over 20</span>
        </div>

        <input
          type="range"
          min="1"
          max="20"
          value={selectedOver}
          onChange={(e) => setSelectedOver(Number(e.target.value))}
          className="range-slider"
        />

        <div style={{ marginTop: '20px' }}>
          <button className="btn btn-primary" onClick={handleCatchUp} disabled={isLoading}>
            {isLoading ? '⏳ Fetching Brief from Backend...' : '⚡ Catch Me Up!'}
          </button>
        </div>
      </div>

      {summary && (
        <div className="glass-card">
          <div className="ai-output-tag">
            📋 Backend Match Brief • Up to Over {selectedOver}
          </div>

          {error && (
            <div style={{ fontSize: '12px', color: '#f5a623', marginBottom: '8px' }}>⚠️ {error}</div>
          )}

          <p style={{ fontSize: '14.5px', lineHeight: '1.7', marginTop: '8px', color: '#e8eef8' }}>
            {summary}
          </p>

          <div style={{ marginTop: '20px', paddingTop: '16px', borderTop: '1px solid var(--border)' }}>
            <span style={{ fontSize: '12px', color: '#8b9db5', fontWeight: '600' }}>
              Ask a quick follow-up:
            </span>
            <div className="claim-tags-row">
              {QUICK_QUESTIONS.map((q, i) => (
                <button key={i} className="claim-tag-btn" onClick={() => handleQuickQuestion(q)}>
                  {q}
                </button>
              ))}
            </div>

            {followup && (
              <div className="ai-output-box" style={{ marginTop: '12px' }}>
                <div className="ai-output-tag">💬 {followup.question}</div>
                <p className="ai-output-text">{followup.answer}</p>
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
